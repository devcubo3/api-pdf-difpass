"""Synthetic HTTP/API/separate-worker smoke. Local provider double; never bills AI.

Creates only its own source fixture. The premium PDF is generated by the API worker
and saved exactly as downloaded. No application imports, real keys or customer files.
All child processes and the local test provider are stopped on exit.
"""
import argparse
import base64
import hashlib
from http.server import BaseHTTPRequestHandler,ThreadingHTTPServer
import io
import json
import os
from pathlib import Path
import secrets
import signal
import socket
import subprocess
import sys
import threading
import time
from uuid import uuid4

import httpx
from reportlab.pdfgen import canvas


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output-dir',type=Path)
    parser.add_argument('--shared-image', help='Exercise both APIs and the worker in this Docker image')
    parser.add_argument('--html-engine',choices=['chromium','weasyprint'],default='chromium')
    parser.add_argument('--review-policy',choices=['always','validated_auto'],default='always')
    parser.add_argument('--budget-recovery',action='store_true',
                        help='Simulate overload, a budget block and an explicit staff retry')
    parser.add_argument('--browser-channel',choices=['chrome','msedge','chromium'],
                        default='chrome' if os.name=='nt' else 'chromium')
    args=parser.parse_args()
    root=Path(__file__).resolve().parents[1]
    output=(args.output_dir or root/'var/test-results'/('canonical-http-'+uuid4().hex[:10])).resolve()
    if not output.is_relative_to((root/'var').resolve()):
        raise RuntimeError('Synthetic evidence must stay in the private var directory')
    output.mkdir(parents=True,exist_ok=False)
    fixture=io.BytesIO()
    pdf=canvas.Canvas(fixture,pagesize=(595,842),invariant=True)
    lines=['LOCACAO - DOCUMENTO SINTETICO','Locadora: SOLARA TESTE',
        'Condutor: VIAJANTE SINTETICO','Reserva: DEMO-000123',
        'Retirada: 31/10/2026 19:00 - MIAMI','Devolucao: 13/11/2026 19:00 - ORLANDO',
        'Condicoes gerais: reconfirme check-in e check-out no hotel.',
        'SEM VALIDADE COMERCIAL - SOMENTE TESTE DE SOFTWARE']
    for index,line in enumerate(lines): pdf.drawString(35,790-index*28,line)
    pdf.showPage(); pdf.save()
    source=fixture.getvalue(); source_sha=hashlib.sha256(source).hexdigest()
    (output/'source-synthetic.pdf').write_bytes(source)
    provider_calls=[]
    class Provider(BaseHTTPRequestHandler):
        def log_message(self,*args): pass
        def do_POST(self):
            try:
                assert self.path=='/v1/responses' and len(provider_calls)<(2 if args.budget_recovery else 1)
                length=int(self.headers.get('Content-Length','0')); assert 0<length<2_000_000
                body=json.loads(self.rfile.read(length))
                assert body['text']['format']['name']=='difftravel_understanding_v1'
                parts=body['input'][0]['content']
                original=base64.b64decode(next(p['file_data'].split(',',1)[1] for p in parts if p['type']=='input_file'))
                assert hashlib.sha256(original).hexdigest()==source_sha
                blocks=json.loads(next(p['text'] for p in parts if p['type']=='input_text'))['blocks']
                def ev(needle):
                    block=next(b for b in blocks if needle in b['text'])
                    return {'block_id':block['id'],'quote':block['text']}
                provider_calls.append('local_test_double')
                if args.budget_recovery and len(provider_calls)==1:
                    raw=json.dumps({'error':{'code':'server_is_overloaded','message':'Synthetic overload'}}).encode()
                    self.send_response(503);self.send_header('Content-Type','application/json')
                    self.send_header('Content-Length',str(len(raw)));self.end_headers();self.wfile.write(raw)
                    return
                understanding={'schema_version':'canonical_v1','primary_place_id':None,'unreadable_code_pages':[],
                    'entities':[{'id':'driver','role':'person','name':'VIAJANTE SINTETICO','locality':None,
                                 'evidence':[ev('Condutor:')]}],
                    'services':[{'id':'rental','kind':'car_rental','name':'SOLARA TESTE','entity_ids':['driver'],
                                 'evidence':[ev('Locadora:'),ev('Retirada:')]}],
                    'facts':[{'id':key,'service_id':'rental','entity_id':None,'kind':key,'label':label,
                              'raw_value':value,'status':'supported','evidence':[ev(label+':')]}
                        for key,label,value in [('rental_reference','Reserva','DEMO-000123'),
                            ('pickup','Retirada','31/10/2026 19:00 - MIAMI'),
                            ('dropoff','Devolucao','13/11/2026 19:00 - ORLANDO')]],
                    'conditions':[{'id':'terms','service_id':None,'kind':'general','evidence':[ev('Condicoes gerais:')]}],
                    'code_associations':[]}
                payload={'id':'resp_synthetic','object':'response','created_at':int(time.time()),
                    'model':'gpt-6-luna','service_tier':'default','status':'completed','output':[{'id':'msg_synthetic',
                        'type':'message','role':'assistant','status':'completed','content':[
                            {'type':'output_text','text':json.dumps(understanding,ensure_ascii=False),'annotations':[]}]}],
                    'usage':{'input_tokens':0,'output_tokens':0,'total_tokens':0}}
                raw=json.dumps(payload).encode()
                self.send_response(200); self.send_header('Content-Type','application/json')
                self.send_header('Content-Length',str(len(raw))); self.end_headers(); self.wfile.write(raw)
            except Exception:
                self.send_response(400); self.end_headers()
    provider=ThreadingHTTPServer(('0.0.0.0' if args.shared_image else '127.0.0.1',0),Provider)
    thread=threading.Thread(target=provider.serve_forever,daemon=True); thread.start()
    with socket.socket() as port_socket:
        port_socket.bind(('127.0.0.1',0)); api_port=port_socket.getsockname()[1]
    base=f'http://127.0.0.1:{api_port}'
    token=secrets.token_urlsafe(32)
    env={k:v for k,v in os.environ.items() if not k.startswith(('OPENAI_','PDF_','DATABASE_URL'))}
    env.update({'OPENAI_API_KEY':'synthetic-local-only','OPENAI_BASE_URL':f'http://127.0.0.1:{provider.server_address[1]}/v1',
        'HTTP_PROXY':'','HTTPS_PROXY':'','ALL_PROXY':'','NO_PROXY':'127.0.0.1,localhost',
        'PDF_API_TOKENS':json.dumps({token:{'tenant_id':'synthetic','subject':'smoke','roles':['upload','read','review']}}),
        'PDF_DATA_DIR':str(output/'runtime'),'DATABASE_URL':'sqlite:///'+(output/'runtime/state.db').as_posix(),
        'PDF_RENDER_MODE':'html_template','PDF_HTML_ENGINE':args.html_engine,'PDF_PIPELINE_VERSION':'canonical_v1','PDF_HTML_BROWSER_CHANNEL':
            '' if args.browser_channel=='chromium' else args.browser_channel,
        'PDF_PUBLIC_BASE_URL':base,'PDF_MEDIA_MODE':'brand','PDF_WORKER_TIMEOUT_SECONDS':'600',
        'PDF_REVIEW_POLICY':args.review_policy,
        'PDF_LEGACY_PDF_HOSTS':json.dumps({'synthetic':['files.example.test']}),
        'PDF_AI_DOCUMENT_BUDGET_USD':'0.20','PDF_AI_DAILY_BUDGET_USD':'0.20'})
    if args.budget_recovery:
        env.update(PDF_AI_DOCUMENT_BUDGET_USD='0.15',PDF_AI_DAILY_BUDGET_USD='1.00')
    processes=[]; logs=[]; shared=None
    def start(name,command,child_env):
        log=(output/(name+'.log')).open('wb'); logs.append(log)
        process=subprocess.Popen([sys.executable,*command],cwd=root,env=child_env,stdout=log,stderr=log,
            creationflags=subprocess.CREATE_NO_WINDOW if os.name=='nt' else 0,start_new_session=os.name!='nt')
        processes.append(process); return process
    try:
        if args.shared_image:
            from shared_smoke_runtime import SharedRuntime
            shared=SharedRuntime(args.shared_image,env,output,api_port)
            api=shared.start()
        else:
            api=start('api',['-m','uvicorn','app.main:app','--host','127.0.0.1','--port',str(api_port),'--no-access-log'],env)
        with httpx.Client(trust_env=False,timeout=30,headers={'Authorization':'Bearer '+token}) as client:
            deadline=time.monotonic()+60
            while True:
                if api.poll() is not None: raise RuntimeError('Synthetic API startup failed; inspect private log')
                try:
                    health=client.get(base+'/healthz')
                    if health.status_code==200 and health.json().get('pipeline_version')=='canonical_v1': break
                except httpx.TransportError: pass
                if time.monotonic()>deadline: raise RuntimeError('Synthetic API startup timeout')
                time.sleep(.2)
            upload=client.post(base+'/v2/documents',headers={'Idempotency-Key':'synthetic-http-v1'},
                data={'legacy_pdf_url':'https://files.example.test/safety.pdf'},
                files={'input_pdf':('source-synthetic.pdf',source,'application/pdf')})
            assert upload.status_code==202
            duplicate=client.post(base+'/v2/documents',headers={'Idempotency-Key':'synthetic-http-v1'},
                data={'legacy_pdf_url':'https://files.example.test/safety.pdf'},
                files={'input_pdf':('source-synthetic.pdf',source,'application/pdf')})
            assert duplicate.status_code==202 and duplicate.json()['document_id']==upload.json()['document_id']
            route=base+'/v2/documents/'+upload.json()['document_id']
            worker_env={**env,'PDF_API_TOKENS':'{}'}
            worker=None if shared else start('worker',['-m','app.worker','--once'],worker_env)
            started=time.monotonic(); deadline=started+90
            while True:
                review=client.get(route+'/review').json()
                if review['status'] not in {'queued','processing'}: break
                if time.monotonic()>deadline: raise RuntimeError('Synthetic worker timeout; no retry')
                time.sleep(.2)
            if args.budget_recovery:
                assert review['issues'][0]['code']=='OPENAI_SERVICE_UNAVAILABLE'
                for attempt in (1,2):
                    if worker:
                        worker.wait(timeout=10);assert worker.returncode==0
                    retry=client.post(route+'/reprocess',headers={'If-Match':review['etag']},
                        json={'reason':f'Explicit synthetic staff retry {attempt}'})
                    assert retry.status_code==202
                    worker=None if shared else start(f'worker-retry-{attempt}',
                        ['-m','app.worker','--once'],worker_env)
                    deadline=time.monotonic()+90
                    while True:
                        review=client.get(route+'/review').json()
                        if review['status'] not in {'queued','processing'}:break
                        if time.monotonic()>deadline:raise RuntimeError('Budget recovery timeout; no retry')
                        time.sleep(.2)
                    if attempt==1:
                        assert review['issues'][0]['code']=='AI_BUDGET_LIMIT'
                        assert review['data']['budget_block']['scope']=='document'
                        assert len(provider_calls)==1
                assert review['budget']['manual_allowance_used']
                assert review['budget']['day_limit_usd']==1
                assert any(e['details'].get('budget_authorization') for e in review['events'])
            assert review['checks'].get('validations_passed'),[x['code'] for x in review['issues']]
            assert review['checks']['html_engine']==args.html_engine
            assert review['data']['document_type']=='car_rental'
            artifact=client.get(route+'/review/pdf'); assert artifact.status_code==200
            assert hashlib.sha256(artifact.content).hexdigest()==review['artifact_sha256']
            (output/'premium-synthetic.pdf').write_bytes(artifact.content)
            for number in range(1,review['checks']['rendered_pages']+1):
                page=client.get(route+f'/pages/{number}.png'); assert page.status_code==200
                (output/f'page-{number:03d}.png').write_bytes(page.content)
            delivered=client.get(route+'/pdf')
            if args.review_policy=='validated_auto':
                assert review['status']=='ready'
                assert review['events'][-1]['action']=='automatic_release'
                assert delivered.status_code==200 and delivered.content==artifact.content
            else:
                assert review['status']=='needs_review' and delivered.status_code==409
            assert len(provider_calls)==(2 if args.budget_recovery else 1)
            if worker:
                worker.wait(timeout=10); assert worker.returncode==0
            if shared:
                shared.verify_recovery(client,base,route.removeprefix(base),review['artifact_sha256'])
                assert len(provider_calls)==(2 if args.budget_recovery else 1)
            report={'kind':'synthetic-http-smoke','generation':'api-and-separate-worker',
                'provider':'local_test_double','real_provider_calls':0,'local_premium_pdf_generation':False,
                'human_approval_performed':False,'review_policy':args.review_policy,
                'automatic_release_performed':args.review_policy=='validated_auto',
                'pipeline_version':'canonical_v1','result':'passed',
                'document_type':'car_rental','pages':review['checks']['rendered_pages'],
                'artifact_sha256':review['artifact_sha256'],'checks':review['checks'],
                'issues':review['issues'],'test_double_requests':len(provider_calls),
                'budget_recovery_verified':args.budget_recovery,
                'budget':review['budget'],
                'single_service':bool(shared),'restart_preserved_artifact':bool(shared)}
            (output/'report.json').write_text(json.dumps(report,ensure_ascii=False,indent=2),encoding='utf-8')
            print(json.dumps({'result':'passed','provider':'local_test_double','real_provider_calls':0,
                'pages':report['pages'],'report':str(output/'report.json')},ensure_ascii=False))
        if shared:
            shared.close(); shared=None
            from shared_smoke_runtime import verify_fallbacks
            verify_fallbacks(args.shared_image,env,output,api_port)
    finally:
        if shared:
            shared.close()
        for process in reversed(processes):
            if process.poll() is None:
                if os.name=='nt':
                    subprocess.run(['taskkill','/PID',str(process.pid),'/T','/F'],capture_output=True)
                else:
                    try: os.killpg(process.pid,signal.SIGTERM)
                    except ProcessLookupError: pass
                try: process.wait(timeout=10)
                except subprocess.TimeoutExpired: process.kill()
        provider.shutdown(); provider.server_close(); thread.join(timeout=5)
        for log in logs: log.close()


if __name__=='__main__': main()
